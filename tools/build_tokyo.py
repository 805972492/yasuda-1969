def write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)


def build():
    os.makedirs(DATA, exist_ok=True)
    os.makedirs(MAP, exist_ok=True)

    ev_rows = []
    for d, tm, place, cat, desc, link, src in EVENTS:
        lat, lon, conf = LOC.get(place, (0, 0, "C"))
        ev_rows.append([d, tm, place, cat, round(lat, 6), round(lon, 6), REL[conf], desc, link, src])
    write_csv(os.path.join(DATA, "tokyo_ops.csv"),
              ["日期", "时刻", "地点", "类别", "纬度", "经度", "坐标可信度", "事件", "与安田讲堂的关联", "出处"], ev_rows)

    write_csv(os.path.join(DATA, "factions.csv"),
              ["派系", "正式名/上部团体", "系统", "主要据点", "本郷兵力(1969-01)", "构内位置", "与全共闘关系", "关键行动", "出处"],
              FACTIONS)

    write_csv(os.path.join(DATA, "impact.csv"),
              ["日期", "类别", "事项", "数据/内容", "影响", "出处"], IMPACT)

    # ---------- 地图数据 ----------
    import datetime
    t0 = datetime.datetime(1969, 1, 15, 0, 0)
    pts = []
    for d, tm, place, cat, desc, link, src in EVENTS:
        hh, mm = tm.split(":")
        dt = datetime.datetime.strptime(d, "%Y-%m-%d").replace(hour=int(hh), minute=int(mm))
        pts.append({
            "t": int((dt - t0).total_seconds() // 60),
            "d": d, "tm": tm, "p": place, "c": cat, "x": desc, "k": link, "s": src,
            "lat": LOC.get(place, (0, 0, "C"))[0], "lon": LOC.get(place, (0, 0, "C"))[1],
        })

    fac_pts = []
    for row in FACTIONS:
        name, org, sys_, base, force, pos, rel, act, src = row
        if name in FAC_LOC:
            lat, lon = FAC_LOC[name]
            cand = name
        else:
            key = base.split("（")[0].split("、")[0]
            cand = "安田講堂"
            for k in LOC:
                if k and (k in base or base in k):
                    cand = k
                    break
            lat, lon = LOC[cand][:2]
        fac_pts.append({"n": name, "o": org, "sys": sys_, "b": base, "f": force,
                        "p": pos, "r": rel, "a": act, "s": src,
                        "lat": lat, "lon": lon, "place": cand})

    tmax = max(p["t"] for p in pts) + 720
    html = HTML_TMPL.replace("__EVENTS__", json.dumps(pts, ensure_ascii=False)) \
                    .replace("__FACTIONS__", json.dumps(fac_pts, ensure_ascii=False)) \
                    .replace("__CATS__", json.dumps(CATS, ensure_ascii=False)) \
                    .replace("__TMAX__", str(tmax))
    out = os.path.join(MAP, "东京全城态势图.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(html)
    print("csv:", len(EVENTS), "events,", len(FACTIONS), "factions,", len(IMPACT), "impact rows")
    print("html:", out, os.path.getsize(out), "bytes")


