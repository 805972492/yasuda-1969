def protect(s):
    """把不能改的段落挖出来，最后原样放回。"""
    slots = []

    def stash(text):
        slots.append(text)
        return "\x00P%d\x00" % (len(slots) - 1)

    # 来源题名与 URL 原样保留（引文出处要能对回日文原题）
    s = re.sub(r'("title": )"([^"]*)"', lambda m: m.group(1) + '"' + stash(m.group(2)) + '"', s)
    s = re.sub(r'("url": )"([^"]*)"', lambda m: m.group(1) + '"' + stash(m.group(2)) + '"', s)
    # aliases 检索别名
    m = re.search(r'"aliases": \[[^\]]*\]', s)
    if m:
        s = s[:m.start()] + stash(m.group(0)) + s[m.end():]
    return s, slots


def restore(s, slots):
    for k, v in enumerate(slots):
        s = s.replace("\x00P%d\x00" % k, v)
    return s


STAT = {}
for name in FILES:
    p = ROOT / name
    s = p.read_text(encoding="utf-8")
    before = s
    slots = []
    if name == "build_campaign.py":
        s, slots = protect(s)
    for a, b in TERMS + WORDS:
        if a in s:
            STAT[a] = STAT.get(a, 0) + s.count(a)
            s = s.replace(a, b)
    out = []
    for ch in s:
        if ch in CHARS:
            out.append(CHARS[ch])
            STAT[ch] = STAT.get(ch, 0) + 1
        else:
            out.append(ch)
    s = "".join(out)
    s = restore(s, slots)
    if s != before:
        p.write_text(s, encoding="utf-8")
        print("updated", name, len(before), "->", len(s))
    else:
        print("no change", name)

